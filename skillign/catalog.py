CATEGORY_BY_SLUG = {category["slug"]: category for category in CATEGORIES}


def _normalize(value):
    decomposed = unicodedata.normalize("NFKD", value.lower())
    return "".join(char for char in decomposed if not unicodedata.combining(char))


def _cover_for(skill, position):
    background, ink, accent = THEMES[skill["category"]][position % 3]
    lines = textwrap.wrap(skill["name"].upper(), width=16, break_long_words=False) or [skill["name"].upper()]
    longest = max(len(line) for line in lines)
    font_size = max(12, min(26, int(164 / (0.62 * longest))))
    line_height = round(font_size * 1.12)
    return {
        "bg": background,
        "ink": ink,
        "accent": accent,
        "motif": MOTIFS[position % len(MOTIFS)],
        "number": f"{skill['_position']:02d}",
        "category": CATEGORY_BY_SLUG[skill["category"]]["label"].upper(),
        "lines": lines,
        "font_size": font_size,
        "line_height": line_height,
        "start_y": 246 - (len(lines) - 1) * line_height,
    }


for index, skill in enumerate(SKILLS):
    skill["_position"] = index + 1
    category = CATEGORY_BY_SLUG[skill["category"]]
    skill["category_label"] = category["label"]
    skill["cover"] = _cover_for(skill, index)
    skill["search_text"] = _normalize(
        " ".join(
            [skill["name"], skill["tagline"], skill["summary"], category["label"]]
            + skill["topics"]
        )
    )

SKILLS_BY_SLUG = {skill["slug"]: skill for skill in SKILLS}


def serialize_skill(skill):
    return {
        "slug": skill["slug"],
        "name": skill["name"],
        "category": skill["category"],
        "category_label": skill["category_label"],
        "level": skill["level"],
        "duration": skill["duration"],
        "format": skill["format"],
        "tagline": skill["tagline"],
        "summary": skill["summary"],
        "topics": skill["topics"],
        "resources": [
            {"label": label, "url": url} for label, url in skill["resources"]
        ],
        "cover": skill["cover"],
    }


def skills_for(category_slug):
    return [skill for skill in SKILLS if skill["category"] == category_slug]


def shelves():
    return [(category, skills_for(category["slug"])) for category in CATEGORIES]


def search_skills(query):
    needle = _normalize(query)
    if not needle:
        return []
    return [skill for skill in SKILLS if needle in skill["search_text"]]


def category_counts():
    counts = {}
    for category in CATEGORIES:
        counts[category["slug"]] = len(skills_for(category["slug"]))
    return counts
